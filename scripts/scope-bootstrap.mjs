// One-off generator: scopes Bootstrap 5.3.3 so it only applies on the /projects page
// (the old site only loaded Bootstrap on projects.html).
// Run: node scripts/scope-bootstrap.mjs
import fs from 'node:fs';
import postcss from 'postcss';

const SCOPE = ':where(.bs-page)';
const src = fs.readFileSync('node_modules/bootstrap/dist/css/bootstrap.min.css', 'utf8');
const root = postcss.parse(src);

const mapSelector = (sel) => {
  sel = sel.trim();
  // root/html/body-level selectors become the scope element itself
  if (sel === ':root' || sel === 'html' || sel === 'body' || sel === '[data-bs-theme=light]') return SCOPE;
  if (sel.startsWith('[data-bs-theme=dark]') || sel.startsWith('[data-bs-theme=')) return null; // unused dark theme
  if (sel.startsWith('html') || sel.startsWith(':root')) return null;
  return `${SCOPE} ${sel}`;
};

root.walkRules((rule) => {
  if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
  const mapped = [...new Set(rule.selectors.map(mapSelector).filter(Boolean))];
  if (!mapped.length) rule.remove();
  else rule.selector = mapped.join(',');
});
root.walkAtRules((a) => { if (a.name === 'media' && !a.nodes?.length) a.remove(); });

// The wrapper div stands in for <body>: don't let Bootstrap override the site's own
// body font/colour/background (the site's body rule already sets those on the real <body>).
root.walkRules(SCOPE, (rule) => {
  rule.walkDecls((d) => {
    if (['font-family', 'color', 'background-color', 'font-size', 'font-weight', 'line-height'].includes(d.prop) && /--bs-body/.test(d.value)) d.remove();
  });
});

const header = '/* AUTO-GENERATED by scripts/scope-bootstrap.mjs — Bootstrap 5.3.3, scoped to .bs-page (/projects only). Do not edit by hand. */\n';
fs.writeFileSync('src/app/bootstrap-scoped.css', header + root.toString());
console.log('written', fs.statSync('src/app/bootstrap-scoped.css').size, 'bytes');
